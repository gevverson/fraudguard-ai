"""
registry.py — model versioning & registry (Pillar B2).

Why: "just save the model to one file" is a dead end. The day it drifts you need
to answer: which model scored this transaction? what data trained it? is the new
one actually better? can we roll back? A registry makes every model an auditable,
versioned artifact — the foundation drift-monitoring (B3) and retraining (B4) need.

Layout on disk:
    models/registry/
      registry.json            <- index: champion pointer + all versions' metadata
      v1/model.joblib          <- the model binary (git-ignored)
      v1/metadata.json         <- data fingerprint, params, metrics, hash, timestamp
      v2/...

The JSON (index + metadata) is committed to git = a permanent audit trail. The
.joblib binaries stay out of git and are regenerated by re-running training.
"""
import hashlib
import json
import os
from datetime import datetime

import joblib

REGISTRY_DIR = "models/registry"
INDEX = os.path.join(REGISTRY_DIR, "registry.json")


def _load_index():
    if os.path.exists(INDEX):
        with open(INDEX) as f:
            return json.load(f)
    return {"champion": None, "versions": {}}


def _save_index(idx):
    os.makedirs(REGISTRY_DIR, exist_ok=True)
    with open(INDEX, "w") as f:
        json.dump(idx, f, indent=2)


def _next_version(idx):
    nums = [int(v[1:]) for v in idx["versions"] if v.startswith("v") and v[1:].isdigit()]
    return f"v{(max(nums) + 1) if nums else 1}"


def register(model, *, metrics, params, data_info, features, notes="", make_champion=True):
    """Save a new model version with full metadata. Returns the version id."""
    idx = _load_index()
    version = _next_version(idx)
    vdir = os.path.join(REGISTRY_DIR, version)
    os.makedirs(vdir, exist_ok=True)

    model_path = os.path.join(vdir, "model.joblib")
    joblib.dump(model, model_path)
    with open(model_path, "rb") as f:
        sha = hashlib.sha256(f.read()).hexdigest()[:16]

    meta = {
        "version": version,
        "created_at": datetime.now().isoformat(timespec="seconds"),
        "metrics": metrics,
        "params": params,
        "data_info": data_info,
        "features": features,
        "model_sha256": sha,
        "notes": notes,
    }
    with open(os.path.join(vdir, "metadata.json"), "w") as f:
        json.dump(meta, f, indent=2)

    idx["versions"][version] = meta
    if make_champion or idx["champion"] is None:
        idx["champion"] = version
    _save_index(idx)
    return version


def list_versions():
    idx = _load_index()
    return idx["versions"], idx["champion"]


def get_champion():
    return _load_index()["champion"]


def set_champion(version):
    """Promote or ROLL BACK to a specific version."""
    idx = _load_index()
    if version not in idx["versions"]:
        raise ValueError(f"unknown version: {version}")
    idx["champion"] = version
    _save_index(idx)


def metadata(version=None):
    idx = _load_index()
    version = version or idx["champion"]
    return idx["versions"].get(version)


def load(version=None):
    """Load a model (champion by default)."""
    idx = _load_index()
    version = version or idx["champion"]
    if version is None:
        raise FileNotFoundError("registry is empty — register a model first")
    return joblib.load(os.path.join(REGISTRY_DIR, version, "model.joblib"))
